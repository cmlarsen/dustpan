use super::{tilde, Ctx, Emit};
use crate::git::gitdir_of;
use crate::model::{Action, Category, Item, Verdict};
use crate::size::dir_stats;
use crate::util::{age_days, human, mtime, newer};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

const SKIP: &[&str] = &["Pods", "build", "DerivedData", "target", "dist", "vendor", ".git"];

pub fn find(roots: &[PathBuf], exclude: &[PathBuf], max_depth: usize) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for r in roots {
        walk(r, max_depth, exclude, &mut out);
    }
    out
}

fn walk(dir: &Path, depth: usize, exclude: &[PathBuf], out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        if !e.file_type().is_ok_and(|t| t.is_dir()) {
            continue;
        }
        let name = e.file_name();
        let name = name.to_string_lossy();
        let path = e.path();
        if name == "node_modules" {
            out.push(path);
            continue;
        }
        if name.starts_with('.') || SKIP.contains(&name.as_ref()) || exclude.contains(&path) {
            continue;
        }
        if depth > 0 {
            walk(&path, depth - 1, exclude, out);
        }
    }
}

pub fn owner_of(nm: &Path, roots: &[PathBuf]) -> PathBuf {
    let mut cur = nm.parent();
    while let Some(dir) = cur {
        if dir.join(".git").exists() {
            return dir.to_path_buf();
        }
        if roots.iter().any(|r| r == dir) {
            break;
        }
        cur = dir.parent();
    }
    nm.parent().unwrap_or(nm).to_path_buf()
}

pub fn scan(ctx: &Ctx, emit: Emit) {
    let exclude = ctx.all_worktree_paths();
    let found = find(&ctx.roots, &exclude, 5);
    let mut groups: BTreeMap<PathBuf, Vec<PathBuf>> = BTreeMap::new();
    for nm in found {
        groups.entry(owner_of(&nm, &ctx.roots)).or_default().push(nm);
    }
    std::thread::scope(|s| {
        for (owner, dirs) in &groups {
            s.spawn(move || emit(build(ctx, owner, dirs)));
        }
    });
}

fn build(ctx: &Ctx, owner: &Path, dirs: &[PathBuf]) -> Item {
    let mut bytes = 0;
    let mut excl = 0;
    let mut installed = None;
    for d in dirs {
        let s = dir_stats(d);
        bytes += s.bytes;
        excl += s.exclusive;
        installed = newer(installed, s.newest);
    }
    let activity = gitdir_of(owner)
        .and_then(|g| mtime(&g.join("logs/HEAD")))
        .or_else(|| mtime(&owner.join("package.json")));
    let mut item = Item::new(
        Category::NodeModules,
        format!("node_modules · {}", tilde(ctx, owner)),
        owner.join("node_modules"),
    );
    item.bytes = bytes;
    item.reclaimable = excl;
    item.last_used = newer(activity, installed);
    item.owner = Some(owner.to_path_buf());
    item.action = Action::delete_all(dirs.to_vec());
    let idle = age_days(activity.or(installed), ctx.now);
    let mut reasons = Vec::new();
    if ctx.stale(idle) {
        item.verdict = Verdict::Review;
        reasons.push(format!(
            "project idle {} days; a reinstall restores it",
            idle.unwrap_or(0)
        ));
    } else {
        item.verdict = Verdict::Active;
        reasons.push(format!("project active {}d ago", idle.unwrap_or(0)));
    }
    if dirs.len() > 1 {
        reasons.push(format!("{} node_modules folders in this project", dirs.len()));
    }
    if excl + (512 << 20) < bytes {
        reasons.push(format!(
            "mostly hardlinks into the pnpm store: deleting frees {}, not {}",
            human(excl),
            human(bytes)
        ));
    }
    item.reasons = reasons;
    item
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn finds_node_modules_but_not_inside_them_or_excluded() {
        let d = tempfile::tempdir().unwrap();
        let r = d.path();
        fs::create_dir_all(r.join("proj/.git")).unwrap();
        fs::create_dir_all(r.join("proj/node_modules/pkg/node_modules")).unwrap();
        fs::create_dir_all(r.join("proj/apps/web/node_modules")).unwrap();
        fs::create_dir_all(r.join("wt/node_modules")).unwrap();
        fs::create_dir_all(r.join("proj/.claude/worktrees/a/node_modules")).unwrap();
        let mut found = find(&[r.to_path_buf()], &[r.join("wt")], 5);
        found.sort();
        assert_eq!(
            found,
            vec![r.join("proj/apps/web/node_modules"), r.join("proj/node_modules")]
        );
        assert_eq!(owner_of(&found[0], &[r.to_path_buf()]), r.join("proj"));
    }
}
